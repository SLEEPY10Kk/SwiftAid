val LocalLanguage = staticCompositionLocalOf { "en" }
val LocalLanguageChange = staticCompositionLocalOf<(String) -> Unit> { {} }

@Composable
fun GlobalLanguageSwitcher(
    modifier: Modifier = Modifier
) {
    val currentCode = LocalLanguage.current
    val onLanguageChange = LocalLanguageChange.current

    var expanded by remember { mutableStateOf(false) }
    val currentLanguage = SupportedLanguages.find { it.code == currentCode } ?: SupportedLanguages[0]

    Box(modifier = modifier, contentAlignment = Alignment.TopEnd) {
        TextButton(onClick = { expanded = true }) {
            Row(verticalAlignment = Alignment.CenterVertically) {
                Icon(Icons.Default.Info, contentDescription = null, modifier = Modifier.size(18.dp), tint = Color.LightGray)
                Spacer(Modifier.width(6.dp))
                Text(
                    text = currentLanguage.name,
                    color = Color.LightGray,
                    fontSize = 14.sp,
                    fontWeight = FontWeight.Medium
                )
                Icon(Icons.Default.ArrowDropDown, contentDescription = null, tint = Color.LightGray)
            }
        }
        DropdownMenu(
            expanded = expanded,
            onDismissRequest = { expanded = false },
            modifier = Modifier.background(Color(0xFF283B5A)).border(1.dp, Color.Gray)
        ) {
            SupportedLanguages.forEach { lang ->
                DropdownMenuItem(
                    text = {
                        Text(
                            lang.name,
                            color = if (lang.code == currentCode) Color(0xFF336CFC) else Color.White
                        )
                    },
                    onClick = {
                        onLanguageChange(lang.code)
                        expanded = false
                    }
                )
            }
        }
    }
}
